#!/usr/bin/env python3
"""Persist and apply Hyprland monitor modes.

Hyprland re-applies every ``hl.monitor(...)`` entry on config reload, so a
resolution changed at runtime with ``hyprctl`` is lost as soon as the config or
the session reloads. This helper keeps per-output overrides in a JSON file,
regenerates ``monitors_user.lua`` (required after ``monitors.lua``) and applies
the change live.
"""
import sys

sys.dont_write_bytecode = True

import json
import os
import subprocess


def config_dir():
    return os.path.join(
        os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config"),
        "hypr",
    )


def state_path():
    return os.path.join(config_dir(), "monitor_overrides.json")


def lua_path():
    return os.path.join(config_dir(), "monitors_user.lua")


def monitors():
    """Return the active Hyprland monitors, or an empty list if unavailable."""
    try:
        raw = subprocess.check_output(
            ["hyprctl", "monitors", "-j"], stderr=subprocess.DEVNULL
        )
        data = json.loads(raw.decode("utf-8"))
    except Exception:
        return []
    return [monitor for monitor in data if not monitor.get("disabled")]


def current_mode(monitor):
    return "{width}x{height}@{refresh:.2f}".format(
        width=monitor["width"],
        height=monitor["height"],
        refresh=float(monitor["refreshRate"]),
    )


def current_entry(monitor):
    return {
        "mode": current_mode(monitor),
        "position": "auto",
        "scale": str(monitor.get("scale", 1)),
    }


def load_state():
    try:
        with open(state_path(), "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except Exception:
        return {}
    return data if isinstance(data, dict) else {}


def write_lua(state):
    lines = ["-- Generated by Minflair Settings; do not edit by hand.", ""]
    for output in sorted(state):
        entry = state[output]
        lines.extend(
            [
                "hl.monitor({",
                '  output = "{}",'.format(output),
                '  mode = "{}",'.format(entry["mode"]),
                '  position = "{}",'.format(entry.get("position", "auto")),
                '  scale = "{}",'.format(entry.get("scale", "1")),
                "})",
                "",
            ]
        )
    path = lua_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    os.replace(tmp, path)


def write_state(state):
    path = state_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(state, handle, indent=2, sort_keys=True)
        handle.write("\n")
    os.replace(tmp, path)
    write_lua(state)


def apply_entry(output, entry):
    spec = "{},{},{},{}".format(
        output,
        entry["mode"],
        entry.get("position", "auto"),
        entry.get("scale", "1"),
    )
    subprocess.run(
        ["hyprctl", "keyword", "monitor", spec],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def apply_all(state):
    for output in sorted(state):
        apply_entry(output, state[output])


def normalize_mode(mode):
    mode = mode.strip()
    if mode.endswith("Hz"):
        mode = mode[:-2]
    return mode


def set_mode(output, mode):
    monitor = next((item for item in monitors() if item["name"] == output), None)
    if monitor is None:
        print("Unknown monitor: {}".format(output), file=sys.stderr)
        return 1

    state = load_state()
    entry = state.get(output, current_entry(monitor))
    entry["mode"] = normalize_mode(mode)
    state[output] = entry
    write_state(state)
    apply_entry(output, entry)
    return 0


def set_scale(scale):
    try:
        number = float(scale)
    except ValueError:
        print("Invalid scale: {}".format(scale), file=sys.stderr)
        return 1
    value = str(int(number)) if number.is_integer() else str(number)

    state = load_state()
    for monitor in monitors():
        name = monitor["name"]
        entry = state.get(name, current_entry(monitor))
        entry["scale"] = value
        state[name] = entry
    write_state(state)
    apply_all(state)
    return 0


def main():
    if len(sys.argv) < 2:
        print(
            "Usage: hypr_monitors.py set-mode <output> <mode> | set-scale <scale>",
            file=sys.stderr,
        )
        return 2

    action = sys.argv[1]
    if action == "set-mode":
        if len(sys.argv) < 4:
            print("set-mode requires <output> <mode>", file=sys.stderr)
            return 2
        return set_mode(sys.argv[2], sys.argv[3])

    if action == "set-scale":
        if len(sys.argv) < 3:
            print("set-scale requires <scale>", file=sys.stderr)
            return 2
        return set_scale(sys.argv[2])

    print("Unknown action: {}".format(action), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
